/**
 * CLI: exports one instance per archetype (seed 42) as a LaTeX catalog for
 * the thesis appendix, grouped by the seven reporting categories.
 *
 *   bun scripts/export-catalog.ts
 *
 * Output: reports/latex/catalog.tex (to be \input in the thesis; needs
 * \usepackage[T1]{fontenc}, \usepackage[utf8]{inputenc}, \usepackage[italian]{babel}).
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { createRng } from "../src/services/combinatorics/math-utils";
import { ARCHETYPES } from "../src/services/combinatorics/combinatorics.service";
import { ENGINE_VERSION, resolveExercise } from "../src/services/combinatorics/engine";
import { CATEGORY_IDS, REPORTING_CATEGORIES } from "../src/services/combinatorics/categories";
import { checkExercise } from "../src/services/combinatorics/oracle";

const SEED = 42;
const out = resolve(process.argv[process.argv.indexOf("--out") + 1] && process.argv.includes("--out")
  ? process.argv[process.argv.indexOf("--out") + 1]!
  : "reports/latex/catalog.tex");

const CATEGORY_TITLES: Record<string, string> = {
  disposizioni: "Disposizioni",
  permutazioni: "Permutazioni",
  combinazioni: "Combinazioni",
  urne: "Urne",
  "probabilita-elementare": "Probabilità elementare",
  "probabilita-avanzata": "Probabilità avanzata",
  trombetta: "Archetipi da Trombetta",
};

const DIFFICULTY_IT: Record<string, string> = { base: "base", intermediate: "intermedio", advanced: "avanzato" };

/* ---------- text → LaTeX ---------- */

function escapeText(s: string): string {
  return s
    .replace(/\\/g, "\u0000")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}")
    .replace(/\u0000/g, "\\textbackslash{}")
    .replace(/«/g, "\\guillemotleft{}")
    .replace(/»/g, "\\guillemotright{}")
    .replace(/“/g, "``")
    .replace(/”/g, "''")
    .replace(/’/g, "'")
    .replace(/…/g, "\\ldots{}")
    .replace(/–/g, "--")
    .replace(/·/g, "$\\cdot$")
    .replace(/−/g, "$-$")
    .replace(/×/g, "$\\times$")
    .replace(/∪/g, "$\\cup$")
    .replace(/∩/g, "$\\cap$")
    .replace(/≥/g, "$\\geq$")
    .replace(/ⁿ/g, "$^{n}$")
    .replace(/²/g, "$^{2}$")
    .replace(/₁/g, "$_{1}$")
    .replace(/₂/g, "$_{2}$");
}

function mathBody(s: string): string {
  return s
    .replace(/·/g, "\\cdot ")
    .replace(/−/g, "-")
    .replace(/×/g, "\\times ")
    .replace(/∪/g, "\\cup ")
    .replace(/∩/g, "\\cap ")
    .replace(/ⁿ/g, "^{n}")
    .replace(/²/g, "^{2}")
    .replace(/₁/g, "_{1}")
    .replace(/₂/g, "_{2}")
    .replace(/…/g, "\\ldots ")
    .replace(/\|/g, "\\mid ")
    .replace(/\^\(([^()]*)\)/g, "^{($1)}")
    .replace(/\^([A-Za-z0-9]+)/g, "^{$1}");
}

/**
 * A math run is a sequence of operands (numbers, n!, C(a,b), single-letter
 * variables, powers) joined by arithmetic operators; it is rendered in $…$.
 */
const OPERAND = String.raw`(?:[CDP]\([^()]*(?:\([^()]*\)[^()]*)*\)|\(\d+\s*[−+]\s*\d+\)!|\d+(?:\/\d+)?!?|\b[a-zA-Z](?=[\^!]|\s*[=·−+×/^]|$)|\b[qpxk]\b)(?:\^(?:\([^()]*\)|[A-Za-z0-9]+))?`;
const MATH_RUN = new RegExp(`${OPERAND}(?:\\s*[·−+×/=]\\s*${OPERAND})*`, "g");

function toLatex(s: string): string {
  let result = "";
  let last = 0;
  for (const m of s.matchAll(MATH_RUN)) {
    const start = m.index ?? 0;
    const run = m[0];
    // plain integers inside prose stay text; anything with an operator, power, factorial or C()/D()/P() becomes math
    const isMath = /[·−+×/=^!(]/.test(run);
    if (!isMath) continue;
    result += escapeText(s.slice(last, start));
    result += `$${mathBody(run)}$`;
    last = start + run.length;
  }
  result += escapeText(s.slice(last));
  return result.replace(/\$\$/g, "");
}

function value(v: string): string {
  return `$${v}$`;
}

/* ---------- catalog ---------- */

const rng = createRng(SEED);
const byId = new Map(ARCHETYPES.map((a) => [a.id, a]));
const lines: string[] = [
  `% generated by scripts/export-catalog.ts — engine v${ENGINE_VERSION}, seed ${SEED}`,
  "% requires \\usepackage[T1]{fontenc}, \\usepackage[utf8]{inputenc}, \\usepackage[italian]{babel}",
  "",
];

for (const category of CATEGORY_IDS) {
  lines.push(`\\section{${CATEGORY_TITLES[category] ?? category}}`, "");
  for (const id of REPORTING_CATEGORIES[category]) {
    const archetype = byId.get(id);
    if (!archetype) throw new Error(`unknown archetype ${id}`);
    const ex = resolveExercise(archetype, rng);
    const problems = checkExercise(ex);
    if (problems.length) throw new Error(`${id}: ${problems.join("; ")}`);
    const diff = DIFFICULTY_IT[ex.difficulty] ?? ex.difficulty;
    lines.push(`\\subsection{\\texorpdfstring{\\texttt{${id}} (${diff})}{${id} (${diff})}}`);
    lines.push("");
    lines.push(`\\paragraph{Quesito.} ${toLatex(ex.text.it)}`);
    lines.push("");
    lines.push(`\\paragraph{Risposta corretta.} ${value(ex.correct)}`);
    lines.push("");
    lines.push(`\\paragraph{Derivazione.} ${toLatex(ex.explanation.it)}`);
    lines.push("");
    lines.push("\\paragraph{Distrattori.}");
    lines.push("\\begin{enumerate}");
    for (const d of ex.distractors) {
      lines.push(`  \\item ${value(d.value)} --- \\texttt{${d.id}} (\\texttt{${d.type}}): ${toLatex(d.diagnosis.it)}`);
    }
    lines.push("\\end{enumerate}", "");
  }
}

const tex = lines.join("\n");
if (/−/.test(tex)) throw new Error("raw Unicode minus left in catalog");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${tex}\n`, "utf8");
console.log(`catalog written to ${out} (${ARCHETYPES.length} archetypes, seed ${SEED})`);
